import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { feature } from 'topojson-client';

const WORLD_TOPO_URL = 'https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json';
const MAP_WIDTH = 960;
const MAP_HEIGHT = 500;
const DOT_SPACING = 2.5;

function project(lat, lon) {
  return {
    x: Number((((lon + 180) / 360) * MAP_WIDTH).toFixed(3)),
    y: Number((((90 - lat) / 180) * MAP_HEIGHT).toFixed(3)),
  };
}

function pointInRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (
      (yi > lat) !== (yj > lat)
      && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    ) {
      inside = !inside;
    }
  }
  return inside;
}

function isPointOnLand(lat, lon, features) {
  for (const item of features) {
    const geometry = item.geometry || item;
    if (geometry.type === 'Polygon') {
      if (pointInRing(lon, lat, geometry.coordinates[0])) return true;
    } else if (geometry.type === 'MultiPolygon') {
      for (const polygon of geometry.coordinates) {
        if (pointInRing(lon, lat, polygon[0])) return true;
      }
    }
  }
  return false;
}

const response = await fetch(WORLD_TOPO_URL);
if (!response.ok) throw new Error(`Failed to fetch world topology: HTTP ${response.status}`);
const topology = await response.json();
const land = feature(topology, topology.objects.land);
const features = land.features || [land];
const dots = [];

for (let lat = 84; lat >= -60; lat -= DOT_SPACING) {
  for (let lon = -180; lon < 180; lon += DOT_SPACING) {
    if (isPointOnLand(lat, lon, features)) dots.push(project(lat, lon));
  }
}

const here = dirname(fileURLToPath(import.meta.url));
const output = resolve(here, '../lib/world-land-dots.generated.ts');
const source = `// Generated by scripts/generate-world-dots.mjs. Do not edit manually.\n`
  + `export const WORLD_LAND_DOTS: ReadonlyArray<Readonly<{ x: number; y: number }>> = `
  + `${JSON.stringify(dots)};\n`;

await writeFile(output, source);
console.log(`Generated ${dots.length} world-map dots at ${output}`);
